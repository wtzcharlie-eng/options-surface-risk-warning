            #
            # **必须取带符号原值 `raw_value`，不能取 `trigger_value`。**
            # 后者对 use_abs 型规则（R2/R3）存的是 |x|——那是为消除
            # 「atm_iv_z = −5.3294，判定为 > 3.5000」这类字面为假的不等式而改的，
            # 改动本身对，但它恰好是方向提示唯一的判据来源，于是方向提示被静默废掉：
            # 全链路复现实测样本里有 1 个 atm_iv_z = −5.33 的截面，提示 0 次触发，
            # 而它正是该功能存在的理由（负向偏离 + 上行机制叙事 + 取 max 的后果口径）。
            # 这类「修 A 静默破坏 B」只有跑完整链路并核对**输出计数**才看得见，
            # 验证门不覆盖（门不检查文案是否出现）。
            zval = None
            win = None
            for e in r["evidence"]:
                d = e["detail"]
                if d.get("trigger_expr"):
                    zval = d.get("raw_value", d.get("trigger_value"))
                    win = d.get("winning_component")
