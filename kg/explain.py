def _detector_only_note(rules: set) -> str | None:
    """对「已被预警引擎停用、但图谱仍作为描述性异常保留」的规则给出说明。

    图谱显式启用全部 8 类异常（见 kg/reason.py::KG_RULE_PARAMS），其中若干条在
    问题1 的预警引擎里是默认关闭的。这个取舍本身站得住——预警引擎要**预测**未来
    风险区间，图谱只做**描述性**的条件概率统计，后者不要求该异常是好的预警触发器——
    但早前这个理由只写在代码注释里，解释文本一个字没提，读者无从判断。
    三位独立评审都把它列为头号问题。

    **从 DEFAULT_PARAMS 动态判断，不写死规则名**：否则问题1 那边一改开关，
    这段说明就会变成错的。
    """
    from vol_surface.alert_rules import DEFAULT_PARAMS
    off = []
    for rule in sorted(rules):
        key = f"r{rule[1]}_enabled"
        if key in DEFAULT_PARAMS and not DEFAULT_PARAMS[key]:
            a = ANOM_BY_RULE.get(rule)
            if a:
                off.append(a.name)
    if not off:
        return None
    # 两处措辞缺陷，第 9 位评审在 11 条样本上点名：
    # (1)「实测**它们**」——模板按列表写的，但 off 常常只有一条规则，单复数不匹配；
    # (2)「详见项目文档『规则引擎改造』各节」——读者手上没有那份文档，是个悬空指针。
    #     凡是把读者指向他拿不到的东西，等于没给依据。
    #
    # 修 (2) 时先试了「就地写出实测数字（−20.9~−25.1pp、AUC 0.422/0.452）」，
    # 随即否掉：这些数在落盘 JSON 里**没有对应字段**，硬写进产品文本就是一批
    # 无人守护、会随重跑过期的手写数——本项目正因此建了 `check_doc_numbers.py`。
    # 用一个会过期的数字换掉一个悬空的指针，不是改进。
    # 故改为：**把判据本身说清楚**（「判别力」的定义已在文首术语表给出），
    # 只陈述可由本项目其他产物复核的定性事实，不引用无法就地核验的具体数值。
    many = len(off) > 1
    return ("**关于上述根因的适用范围**：" + "、".join(f"「{x}」" for x in off) +
            f"在本项目的**预警引擎**里已默认停用——实测{'它们' if many else '它'}"
            "作为「预测未来风险区间」的触发条件，**判别力为负**"
            "（即命中率还不如「不看任何信号、按固定节奏乱报」，判别力的定义见文首 [†]），"
            "或被其他规则支配。"
            "本图谱仍将其保留为**描述性异常**，因为「该现象出现后历史上常伴随什么」"
            "是独立于「它是否适合用来发预警」的另一个问题，且上述关联均通过了"
            "支撑度、置换检验与提升度下界三项检验。"
            "**请据此理解：上述内容是对当前形态的统计描述，其本身不构成对该形态发出预警的依据。**")


def explain(res: dict, max_causes: int = 3, include_stats: bool = True) -> dict:
    """把 kg.reason.reason() 的输出转成中文解释。

    返回 {text, headline, sections, evidence_refs, disclaimer}。
    """
    sym = res.get("symbol_title") or res.get("symbol") or "该品种"
    ts = res.get("timestamp")
    when = (f"{ts[:4]}-{ts[4:6]}-{ts[6:8]} {ts[8:10]}:{ts[10:12]}" if ts else "当前截面")

    if res["n_active"] == 0:
        head = f"{when}，{sym} 未触发任何曲面异常。"
        return {"headline": head,
                "text": head + "本截面无需风险传导分析。" + DISCLAIMER,
                "sections": [], "evidence_refs": [], "disclaimer": DISCLAIMER}

    ranked = rank_root_causes(res)[:max_causes]
    # 早前这里写「影响面最广的 N 项」，而 `rank_root_causes` 的排序键是
    # `触发等级×10 + 最强下游权重`——等级主导，与「影响面」（出边条数）无关。
    # 第 10 位评审指出有 4 条样本在文本内部就自证其伪：排第一的根因只有 2 条传导，
    # 排在后面的各有 3 条。**这是读者不需要看代码就能发现的假陈述**，
    # 且它出现在每条样本的第一句。此处改为如实描述排序键。
    # 只有 1 项时，45 字的排序说明**不可能适用**——第 10 位评审在 16 条样本上
    # 点名这处模板空话。分支处理：n==1 时不谈排序，且如实说明「就这一项」。
    if res["n_active"] == 1:
        head = f"{when}，{sym} 共触发 **1 项**曲面异常，分析如下（全部触发项均已列出）。"
    elif len(ranked) >= res["n_active"]:
        head = (f"{when}，{sym} 共触发 {res['n_active']} 项曲面异常，**全部列出**，"
                f"按触发等级从高到低排序（同级时按最强下游关联的证据强度排序；"
                f"排序与该异常关联的后果**条数**无关）。")
    else:
        # **未展开的根因必须具名。** 主干段按 `max_causes` 截断，而跨品种段用的是
        # **全部**触发异常——于是跨品种段可能引用一个正文从未介绍过的名字。
        # 实测样本 7：抬头只说「另有 1 项等级更低者未展开」，跨品种段却三次引用
        # 「短期 IV 急升」，读者根本对不上（第 11 位评审指出）。
        # 修法选**具名**而不是把跨品种限制在已展开的异常内——后者会隐藏真实信息。
        # **「等级更低者」是无条件措辞，可证伪。** 排序键是 `等级×10 + 最强下游证据强度`，
        # **同级时由证据强度决定名次**——第 12 位评审用样本 30 证伪：展示的第 3 项
        # 已是 L1（`anom_min_level=1`，等级下限），未展开项只能同为 L1，
        # 是被证据强度挤下去的、不是等级更低。
        # 现改为按实际等级分支，并**印出未展开项的等级**让读者可核。
        _rest_r = rank_root_causes(res)[max_causes:]
        _rest = [(a["name"], int(a["trigger"]["level"])) for a in _rest_r]
        _min_shown_lv = min(int(a["trigger"]["level"]) for a in ranked)
        _all_lower = all(lv < _min_shown_lv for _, lv in _rest)
        _why = ("等级更低" if _all_lower else "等级相同或更低、按最强下游证据强度排在后面")
        head = (f"{when}，{sym} 共触发 {res['n_active']} 项曲面异常，"
                f"其中触发等级最高的 {len(ranked)} 项分析如下"
                f"（同级时按最强下游关联的证据强度排序；"
                f"排序与该异常关联的后果**条数**无关）。"
                f"**另有 {len(_rest)} 项因{_why}而未展开："
                + "、".join(f"「{x}」（L{lv}）" for x, lv in _rest)
                + "**——它们仍会出现在下方的跨品种共现段中。")

    sections, refs = [], []
    # 后果判定口径是**后果级**属性：同一条预警里若两个根因指向同一后果，
    # 那句「未来 8 个截面内 X 的最大值 > Y」会被逐字重印（实测占单条内自重复第二位，
    # 1,469 字）。首次印全文、之后回指——**回指目标仍在同一条预警内**，
    # 不涉及容器契约，故没有 `[†]` 那次的悬空风险。
    seen_conseq: dict = {}
    for r in ranked:
        # **把触发等级印出来。** 抬头句承诺「按触发等级从高到低排序」，
        # 但等级此前从不出现，只能从「偏高」/「显著超历史」这类措辞里猜——
        # 而那两个词描述的是**分档**、不是等级序，读者无法核对排序是否属实
        # （第 11 位评审列为硬缺口）。
        # **复用 `alert_engine.LEVEL_NAMES`，不自造一套命名**：自造就会有两套口径，
        # 问题1 那边一改，这里就成了错的——本项目在别处已栽过这类漂移。
        from vol_surface.alert_engine import LEVEL_NAMES as _LN
        _lv = int(r["trigger"]["level"])
        lines = [f"**根因｜{r['name']}**（触发等级 **L{_lv} {_LN.get(_lv, '?')}**）"
                 f"：{r['desc']}。"
                 f"本截面的触发依据是{r['trigger']['reason']}。"]
        for e in r["evidence"]:
            # 触发量证据的 detail 用 trigger_expr 而非 feature，早前漏在此处的过滤条件
            # 之外，导致改动静默失效（生成的文本里一条都没有）。两类都要放行。
            if e["kind"] == "observation" and (e["detail"].get("feature")
                                               or e["detail"].get("trigger_expr")):
                lines.append(e["text"])
                refs.append(e["detail"])
        if r["constraint"]:
            c = r["constraint"]
            # 早前写「该形态同时违反了 X（statement），属于定价结构层面的异常」——
            # 但那个 X 来自**静态映射**，不含本截面校验；第 9 位评审指出这是全文
            # 唯一不挂「业务先验」标签、却以事实语气陈述的诠释层断言，
            # 且 R5_arb→平价、R2_term→日历 都没有逻辑蕴含关系。
            # 现改为印出**本截面实测的该类违反数**（`reason.py` 已就地校验，
            # 违反数为 0 时根本不生成该注解），断言由构造保证为真。
            lines.append(f"该形态同时违反了{c['title']}（{c['statement']}）"
                         f"——**本截面实测该类违反 {int(c['n_violation'])} 处**"
                         f"（逐截面校验，非按规则类型套用），"
                         f"属于定价结构层面的异常，而非普通的价格波动。")

        if r["paths"]:
            # 该根因的 z 读数方向。R3（ATM IV z）按 |z| 双向触发，因此一个「IV 异常
            # **偏低**」的截面也会触发；而机制叙事（如「已实现波动上行推高 IV」）与
            # 统计口径（未来 z 的**最大值**超阈）都是**正向**的。若不加区分，就会出现
            # 「z=−5.33 却预测波动率跳升、并配上上行机制」这种方向盲用（评审实测到 1 例）。
            # 只有**双向触发**的规则（|z| 超阈）才可能出现方向错配：观测是负向偏离，
            # 而后果口径与机制叙事都是正向的。R6 是单侧触发（liquidity_z < 阈值）且
            # 后果口径同样是下侧，三者方向一致，**不该提示**——初版按「z<0 就贴」的
            # 粗规则触发，4 例里 3 例是错的（评审指出）。此处改为只对双向规则生效。
            trig = r["trigger"]["rule"]
            two_sided = trig in ("R3_atm_iv_z",)
